import type { Plugin } from '@terrazzo/parser';

/**
 * Writes one fully resolved token file per brand: <dir>/<brand>.json.
 *
 * Flat map of token ID → { $type, $value, aliasOf? }, aliases resolved to
 * concrete values (colors keep their OKLCH components and sRGB `hex`).
 * Consumers: contrast checking, the Remix "{n} tokens changed" readout,
 * downloadable exports, and later the Figma export. Written under public/
 * so `astro build` ships it at /tokens/<brand>.json.
 */
export default function resolvedJson({ dir, brands }: { dir: string; brands: string[] }): Plugin {
  return {
    name: 'resolved-json',
    build({ resolver, outputFile }) {
      for (const brand of brands) {
        const set = resolver.apply({ brand });
        const tokens: Record<string, { $type: string; $value: unknown; aliasOf?: string }> = {};
        for (const id of Object.keys(set).sort()) {
          const token = set[id]!;
          tokens[id] = { $type: token.$type, $value: token.$value, ...(token.aliasOf && { aliasOf: token.aliasOf }) };
        }
        const doc = { $description: `Resolved tokens for brand "${brand}". GENERATED by pnpm tokens. Do not edit.`, brand, tokens };
        outputFile(`${dir}/${brand}.json`, JSON.stringify(doc, null, 2) + '\n');
      }
    },
  };
}
