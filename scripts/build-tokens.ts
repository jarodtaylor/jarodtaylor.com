/**
 * CLI wrapper around derive(): tokens/knobs/<brand>.json → tokens/generated/<brand>.json.
 * Node-only concerns (filesystem, brand discovery) live here so derive() stays pure.
 * Run via `pnpm tokens`, which then hands the generated sets to Terrazzo.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { basename } from 'node:path';
import { derive, type Knobs } from './derive.ts';
import { brandsFromResolver } from './brands.ts';

const root = new URL('../tokens/', import.meta.url);
const knobsDir = new URL('knobs/', root);
const generatedDir = new URL('generated/', root);

const knobBrands = readdirSync(knobsDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => basename(f, '.json'))
  .sort();

// A brand exists only if it has both knobs and a resolver context. Fail loudly on drift.
const resolverBrands = [...brandsFromResolver().all].sort();
if (knobBrands.join() !== resolverBrands.join()) {
  throw new Error(
    `Brand mismatch: tokens/knobs has [${knobBrands}] but tokens/resolver.json "brand" modifier has [${resolverBrands}]`,
  );
}

const knobsByBrand = new Map(
  knobBrands.map((brand) => [brand, JSON.parse(readFileSync(new URL(`${brand}.json`, knobsDir), 'utf8')) as Knobs]),
);

// The semantic tier aliases color roles, so every brand must define the same ones.
const roleNames = (knobs: Knobs) => Object.keys(knobs.color?.role ?? {}).filter((k) => !k.startsWith('$'));
const allRoles = [...new Set([...knobsByBrand.values()].flatMap(roleNames))].sort();
const missingRoles = [...knobsByBrand].flatMap(([brand, knobs]) =>
  allRoles.filter((role) => !roleNames(knobs).includes(role)).map((role) => `tokens/knobs/${brand}.json is missing color.role.${role}`),
);
if (missingRoles.length) throw new Error(`Color role mismatch (every brand defines the same roles):\n  - ${missingRoles.join('\n  - ')}`);

// Derive every brand before touching tokens/generated/, so a bad knob leaves the old output in place.
const outputs = [...knobsByBrand].map(([brand, knobs]) => ({
  brand,
  output: { $description: `GENERATED by scripts/derive.ts from tokens/knobs/${brand}.json. Do not edit.`, ...deriveOrExplain(brand, knobs) },
}));

rmSync(generatedDir, { recursive: true, force: true });
mkdirSync(generatedDir, { recursive: true });

for (const { brand, output } of outputs) {
  writeFileSync(new URL(`${brand}.json`, generatedDir), JSON.stringify(output, null, 2) + '\n');
  console.log(`derived tokens/generated/${brand}.json`);
}

/** derive() names the bad knob; this adds which brand's file it is in. */
function deriveOrExplain(brand: string, knobs: Knobs) {
  try {
    return derive(knobs);
  } catch (error) {
    throw new Error(`tokens/knobs/${brand}.json: ${(error as Error).message}`, { cause: error });
  }
}
